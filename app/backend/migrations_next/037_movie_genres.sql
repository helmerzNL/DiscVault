-- Tokenize every legacy combined genre string (split on comma/slash/pipe/
-- semicolon/ampersand and a handful of language-neutral conjunctions), then
-- alias-map each token. Kept in a temp table so the insert and the audit
-- trail below are computed from a single, consistent tokenization pass.
CREATE TEMP TABLE _genre_migration_tokens ON COMMIT DROP AS
SELECT
    m.id AS movie_id,
    trim(m.metadata->>'genre') AS raw_value,
    trim(token) AS token,
    lookup.genre_key AS genre_key
FROM movies m
CROSS JOIN LATERAL regexp_split_to_table(
    trim(m.metadata->>'genre'),
    '\s*(?:,|/|\||;|&|、|・)\s*|\s+(?:and|en|und|et)\s+',
    'i'
) AS token
LEFT JOIN _genre_alias_lookup lookup ON lower(trim(token)) = lookup.alias
WHERE m.metadata ? 'genre'
  AND trim(COALESCE(m.metadata->>'genre', '')) <> '';

DELETE FROM _genre_migration_tokens WHERE token = '';

INSERT INTO movie_genres (movie_id, genre_key)
SELECT DISTINCT movie_id, genre_key
FROM _genre_migration_tokens
WHERE genre_key IS NOT NULL
ON CONFLICT (movie_id, genre_key) DO NOTHING;

INSERT INTO movie_genre_migration_audit (movie_id, raw_value, matched_keys, unmatched_parts)
SELECT
    movie_id,
    max(raw_value),
    COALESCE(jsonb_agg(DISTINCT genre_key) FILTER (WHERE genre_key IS NOT NULL), '[]'::jsonb),
    COALESCE(jsonb_agg(DISTINCT token) FILTER (WHERE genre_key IS NULL), '[]'::jsonb)
FROM _genre_migration_tokens
GROUP BY movie_id
ON CONFLICT (movie_id) DO NOTHING;

-- The legacy scalar is fully superseded by movie_genres; drop it so no code
-- path can accidentally read a stale combined-string genre value again.
UPDATE movies SET metadata = metadata - 'genre' WHERE metadata ? 'genre';

-- Genre is no longer a lockable field (it is read-only and TMDB-owned), so
-- drop any stale "genre" entry left over in a movie's field lock list.
UPDATE movies
SET metadata = jsonb_set(
    metadata,
    '{field_locks}',
    COALESCE(
        (
            SELECT jsonb_agg(value)
            FROM jsonb_array_elements(metadata->'field_locks') AS value
            WHERE value <> '"genre"'::jsonb
        ),
        '[]'::jsonb
    )
)
WHERE metadata->'field_locks' @> '["genre"]'::jsonb;

UPDATE movies
SET metadata = jsonb_set(
    metadata,
    '{fieldLocks}',
    COALESCE(
        (
            SELECT jsonb_agg(value)
            FROM jsonb_array_elements(metadata->'fieldLocks') AS value
            WHERE value <> '"genre"'::jsonb
        ),
        '[]'::jsonb
    )
)
WHERE metadata->'fieldLocks' @> '["genre"]'::jsonb;
