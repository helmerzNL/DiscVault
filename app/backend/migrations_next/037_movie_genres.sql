-- DiscVault Next: canonical TMDB movie genre catalog + relational
-- movie_genres associations, replacing the legacy free-text
-- movies.metadata->>'genre' scalar (which stored comma-joined, possibly
-- combined and/or non-English labels).
--
-- TMDB genre ids are the source of truth: `genres.id` mirrors TMDB's
-- numeric movie genre id, `genres.key` is the stable ASCII key stored on
-- `movie_genres` and returned by the API. Locale labels are resolved only
-- at render time from the frontend i18n catalogs (`genre.<key>` keys) --
-- nothing here is locale-dependent.

CREATE TABLE IF NOT EXISTS genres (
    id         integer PRIMARY KEY,
    key        text UNIQUE NOT NULL,
    sort_order integer NOT NULL
);

