CREATE TABLE IF NOT EXISTS movie_genres (
    movie_id   uuid NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
    genre_key  text NOT NULL REFERENCES genres(key) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (movie_id, genre_key)
);

CREATE INDEX IF NOT EXISTS idx_movie_genres_genre ON movie_genres(genre_key);

-- Audit trail for the one-time legacy `metadata->>'genre'` migration below.
-- Keeps the original raw text plus any tokens that couldn't be mapped to a
-- canonical genre, so unrecognized legacy data stays inspectable without
-- ever being surfaced as a genre.
CREATE TABLE IF NOT EXISTS movie_genre_migration_audit (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    movie_id        uuid NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
    raw_value       text NOT NULL,
    matched_keys    jsonb NOT NULL DEFAULT '[]'::jsonb,
    unmatched_parts jsonb NOT NULL DEFAULT '[]'::jsonb,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (movie_id)
);

